/**
 * The raw-selector differential, one entry against the replaced Playwright one.
 *
 * The original public entry (`browser.locator(selector)` at e557432) projected a
 * raw selector straight onto `page.locator(selector)`, so Playwright 1.64.1 is
 * the reference: the oracle below is that same client, on the same page, in the
 * same Chromium the native engine owns, not a reimplementation or a DOM double.
 * `baseline.json` freezes what it returned for every selector in `cases.ts`;
 * the run re-checks that freeze, then compares the current native entry and
 * keeps each disagreement in `expected.txt` with its reason.
 *
 * A refusal here means the call threw. The original entry surfaced every
 * Playwright selector error as `ENGINE_FAILURE`; the native entry classifies
 * user syntax as `INVALID_LOCATOR` and an unimplemented engine as
 * `UNSUPPORTED_CAPABILITY`. Both are refusals, so the comparison treats
 * refusal-vs-refusal as parity and records the current code, while a refusal
 * against a match (in either direction) is a real difference.
 *
 * `E2E_RAW_PARITY_UPDATE=1` regenerates both committed files. The fixture, the
 * Playwright version, the Chromium version and the original revision are
 * checked on every run, so a stale reference fails instead of passing quietly.
 */

import { createRequire } from 'node:module';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { afterAll, beforeAll, expect, it } from 'vitest';
import type { Browser } from '../../src/index.ts';
import { nativeDocument } from '../helpers/native-browser.ts';
import { startNativeOracle, type NativeOracle } from '../helpers/native-oracle.ts';
import { RAW_LOCATOR_CASES } from '../parity/cases.ts';
import {
  diffExpectations,
  fixtureSha256,
  keyOf,
  normalizeOracleError,
  readExpectations,
  sameOutcome,
  TODO_REASON,
  writeExpectations,
  type Baseline,
  type Outcome,
} from '../parity/differential.ts';
import { RAW_LOCATOR_FIXTURE_HTML } from '../parity/fixture.ts';

const DIR = path.join(import.meta.dirname, '../parity');
const BASELINE = path.join(DIR, 'baseline.json');
const EXPECTED = path.join(DIR, 'expected.txt');
const UPDATE = process.env['E2E_RAW_PARITY_UPDATE'] === '1';
const PLAYWRIGHT = createRequire(import.meta.url)('playwright-core/package.json') as { version: string };
/** The last revision whose public entry handed a raw selector to Playwright. */
const ORIGINAL_REVISION = 'e557432eb8e535e5862d9ede7eb40c1d92da0948';
const ORIGINAL_ENTRY = 'packages/web/src/browser.ts@e557432 locator() -> locators.ts projectExpression case selector -> scope.locator(selector)';
const EXPECTED_HEADER = [
  '# Raw selectors on which the native entry disagrees with the replaced Playwright entry.',
  '# family | selector | ours <outcome> | theirs <outcome> | reason',
  '# Generated by E2E_RAW_PARITY_UPDATE=1; edit only the reasons. See tests/parity/differential.ts.',
].join('\n');
const FAMILIES = new Set(RAW_LOCATOR_CASES.map(testCase => testCase.family));

let fixture: NativeOracle | undefined;

beforeAll(async () => {
  fixture = await startNativeOracle('raw-locator-parity', 900_000);
  await nativeDocument(fixture.browser, RAW_LOCATOR_FIXTURE_HTML);
}, 120_000);

afterAll(async () => { await fixture?.close(); });

/** The current public entry: `browser.locator(selector)` on the native engine. */
async function currentEntry(browser: Browser, selector: string): Promise<Outcome> {
  try {
    const matches = await browser.locator(selector).all();
    const ids: string[] = [];
    for (const match of matches) ids.push((await match.getAttribute('data-id')) ?? '<no data-id>');
    return { ids, error: null };
  } catch (cause) {
    const code = cause !== null && typeof cause === 'object' && typeof (cause as { code?: unknown }).code === 'string'
      ? (cause as { code: string }).code
      : cause instanceof Error ? cause.name : 'ERROR';
    return { ids: [], error: code };
  }
}

/** The replaced public entry's result: Playwright's own locator on the same page. */
async function originalEntry(oracle: NativeOracle, selector: string): Promise<Outcome> {
  try {
    const ids = await oracle.oracle.locator(selector).evaluateAll(elements => elements.map(element => element.getAttribute('data-id') ?? '<no data-id>'));
    return { ids, error: null };
  } catch (cause) {
    return { ids: [], error: normalizeOracleError(cause) };
  }
}

function sameFrozen(live: Outcome, frozen: Outcome): boolean {
  return live.error === frozen.error && live.ids.join('\u0000') === frozen.ids.join('\u0000');
}

it('differs from the replaced Playwright entry only where expected.txt says so', async () => {
  const live = fixture!;
  const chromium = live.oracle.context().browser()?.version() ?? 'unknown';

  if (UPDATE) {
    const cases = [];
    for (const testCase of RAW_LOCATOR_CASES) cases.push({ ...testCase, ...await originalEntry(live, testCase.selector) });
    const next: Baseline = {
      schemaVersion: 1,
      oracle: { playwright: PLAYWRIGHT.version, chromium, originalRevision: ORIGINAL_REVISION, originalEntry: ORIGINAL_ENTRY },
      fixtureSha256: fixtureSha256(RAW_LOCATOR_FIXTURE_HTML),
      cases,
    };
    writeFileSync(BASELINE, `${JSON.stringify(next, null, 2)}\n`);
    const seen = new Set<string>();
    for (const [index, testCase] of RAW_LOCATOR_CASES.entries()) {
      const ours = await currentEntry(live.browser, testCase.selector);
      const theirs = next.cases[index]!;
      if (!sameOutcome(ours, theirs)) seen.add(keyOf(testCase, ours, theirs));
    }
    writeExpectations(EXPECTED, EXPECTED_HEADER, existsSync(EXPECTED) ? readExpectations(EXPECTED) : new Map(), seen, FAMILIES);
    return;
  }

  const baseline = JSON.parse(readFileSync(BASELINE, 'utf8')) as Baseline;
  // The frozen reference must still be the real engine's answer.
  expect(baseline.schemaVersion, 'baseline schema').toBe(1);
  expect(baseline.oracle.playwright, 'the reference was recorded with playwright-core 1.64.1').toBe(PLAYWRIGHT.version);
  expect(baseline.oracle.chromium, 'the reference was recorded with this Chromium').toBe(chromium);
  expect(baseline.oracle.originalRevision, 'the reference names the replaced public entry').toBe(ORIGINAL_REVISION);
  expect(baseline.fixtureSha256, 'the fixture is the one the reference was recorded on').toBe(fixtureSha256(RAW_LOCATOR_FIXTURE_HTML));
  expect(baseline.cases.map(testCase => testCase.selector), 'baseline covers the case matrix in order').toEqual(RAW_LOCATOR_CASES.map(testCase => testCase.selector));

  const drift: string[] = [];
  const seen = new Set<string>();
  for (const [index, testCase] of RAW_LOCATOR_CASES.entries()) {
    const frozen = baseline.cases[index]!;
    const theirs = await originalEntry(live, testCase.selector);
    if (!sameFrozen(theirs, frozen)) drift.push(`${testCase.family} ${testCase.selector}: recorded ${JSON.stringify({ ids: frozen.ids, error: frozen.error })} live ${JSON.stringify(theirs)}`);
    const ours = await currentEntry(live.browser, testCase.selector);
    if (!sameOutcome(ours, frozen)) seen.add(keyOf(testCase, ours, frozen));
  }
  expect(drift, `the frozen reference moved; regenerate after reviewing the cause:\n${drift.join('\n')}`).toEqual([]);

  const expected = readExpectations(EXPECTED);
  expect([...expected.values()].filter(reason => reason === TODO_REASON), 'every kept difference states its reason').toEqual([]);
  const { unexpected, stale } = diffExpectations(expected, seen, FAMILIES);
  expect(unexpected, [
    'raw selectors the current entry now disagrees on (add each to expected.txt with its reason, or fix it):',
    ...unexpected.map(key => `${key}${' | '}${TODO_REASON}`),
  ].join('\n')).toEqual([]);
  expect(stale, [
    'expected.txt keeps differences that no longer happen (remove each line; a fix is a reviewable deletion):',
    ...stale,
  ].join('\n')).toEqual([]);
}, 900_000);
