/**
 * The engine's tree against Chrome's accessibility tree and Playwright's
 * `getByRole` on the fixture pages, and on every web-benchmark scenario when
 * `CROSSCHECK_BENCHMARK_URL` names a running benchmark app. Disagreements
 * must match `tests/crosscheck/expected.txt`; `E2E_CROSSCHECK_UPDATE=1`
 * rewrites it (see `tests/crosscheck/expectations.ts`).
 */

import path from 'node:path';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { nativeDocument } from '../helpers/native-browser.ts';
import { startNativeOracle, type NativeOracle } from '../helpers/native-oracle.ts';
import { crossCheck } from '../crosscheck/crosscheck.ts';
import { diffExpectations, keyOf, readExpectations, TODO_REASON, writeExpectations } from '../crosscheck/expectations.ts';
import { FIXTURE_PAGES } from '../crosscheck/fixtures.ts';

const EXPECTED = path.join(import.meta.dirname, '../crosscheck/expected.txt');
const HEADER = [
  '# Known disagreements between the engine tree and Chrome or Playwright, one per line:',
  '# page | oracle field | role "name" | ours <value> | theirs <value> | reason',
  '# Generated by E2E_CROSSCHECK_UPDATE=1; edit only the reasons. See tests/crosscheck/expectations.ts.',
].join('\n');
const BENCHMARK = process.env['CROSSCHECK_BENCHMARK_URL'];
const UPDATE = process.env['E2E_CROSSCHECK_UPDATE'] === '1';

let fixture: NativeOracle | undefined;
const seen = new Set<string>();
const pages = new Set<string>();

beforeAll(async () => {
  // This graph is shared by the 10-minute scenario loop and the fixture tests.
  // Navigation retains its 30-second deadline; action and assertion timeouts are unchanged.
  fixture = await startNativeOracle('crosscheck', 600_000 + (FIXTURE_PAGES.length + 2) * 30_000);
});
afterAll(async () => { await fixture?.close(); });

/** Checks the page as loaded and records its disagreements under `name`. */
async function check(name: string): Promise<void> {
  const result = await crossCheck(fixture!);
  expect(result.compared, `${name} compared no node`).toBeGreaterThan(0);
  if (name === 'benchmark: file-round-trip') {
    const hostCount = await fixture!.oracle.locator('input[type="file"]').count();
    const uploadHostCount = await fixture!.oracle.locator('input[type="file"][data-testid="upload-input"]').count();
    process.stdout.write(`CROSSCHECK_FILE_INPUT_FACTS ${JSON.stringify({ scenario: 'file-round-trip', hostCount, uploadHostCount, fileInputs: result.fileInputs })}\n`);
    expect(hostCount, 'file-round-trip must retain its original single file-input host').toBe(1);
    expect(uploadHostCount, 'file-round-trip must retain the upload-input host after marker restoration').toBe(1);
    expect(result.fileInputs, 'file-round-trip must correlate the real file-input host to a protected ref and Chrome AX node').toHaveLength(1);
    for (const pair of result.fileInputs) {
      for (const value of Object.values(pair)) expect(value.trim().length, 'file-input roles and names must be non-empty').toBeGreaterThan(0);
      expect(pair.nativeRole).toBe(pair.chromeRole);
      expect(pair.nativeName).toBe(pair.chromeName);
    }
  }
  pages.add(name);
  for (const disagreement of result.disagreements) seen.add(keyOf(name, disagreement));
}

describe('cross-check', () => {
  for (const fixturePage of FIXTURE_PAGES) {
    it(`fixture: ${fixturePage.name}`, async () => {
      await nativeDocument(fixture!.browser, `<!doctype html><html lang="en"><body>${fixturePage.html}</body></html>`);
      await check(`fixture: ${fixturePage.name}`);
    });
  }

  describe.skipIf(BENCHMARK === undefined)('web-benchmark scenarios', () => {
    it('every scenario', { timeout: 600_000 }, async () => {
      await fixture!.browser.goto(BENCHMARK!);
      const slugs = await fixture!.browser.evaluate(() =>
        [...new Set([...document.querySelectorAll<HTMLAnchorElement>('a[href^="/e/"]')].map(link => new URL(link.href).pathname.slice('/e/'.length)))]);
      expect(slugs.length).toBeGreaterThan(0);
      for (const slug of slugs.toSorted()) {
        let phase = 'goto';
        try {
          await fixture!.browser.goto(new URL(`/e/${slug}`, BENCHMARK).href, { waitUntil: 'networkidle' });
          phase = 'check';
          await check(`benchmark: ${slug}`);
        } catch (error) {
          const scenario = /^[a-z0-9-]{1,100}$/i.test(slug) ? slug : 'unrecognized-slug';
          process.stderr.write(`CROSSCHECK_SCENARIO_FAILURE ${JSON.stringify({ scenario, phase })}\n`);
          throw error;
        }
      }
      process.stdout.write(`CROSSCHECK_SCENARIOS_COMPLETE ${JSON.stringify({ count: slugs.length })}\n`);
    });
  });

  it('matches the expectations', () => {
    const expected = readExpectations(EXPECTED);
    if (UPDATE) {
      writeExpectations(EXPECTED, HEADER, expected, seen, pages);
      return;
    }
    const { unexpected, stale } = diffExpectations(expected, seen, pages);
    const todo = [...expected].filter(([key, reason]) => pages.has(key.slice(0, key.indexOf(' | '))) && reason === TODO_REASON).map(([key]) => key);
    // Preserve bounded synthetic-fixture diagnostics in Vitest's JSON failure message.
    const details = JSON.stringify({
      unexpected: unexpected.filter(key => key.startsWith('fixture: ')),
      stale: stale.filter(key => key.startsWith('fixture: ')),
      todo: todo.filter(key => key.startsWith('fixture: ')),
    }).slice(0, 16_384);
    expect({ unexpected, stale, todo }, `review tests/crosscheck/expected.txt without rewriting expectations; fixture differences: ${details}`).toEqual({
      unexpected: [],
      stale: [],
      todo: [],
    });
  });
});
